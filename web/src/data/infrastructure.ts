export type SubsystemCategory =
  | 'system'
  | 'compute'
  | 'network'
  | 'security'
  | 'orchestration'
  | 'automation'
  | 'observability'
  | 'services'
  | 'elo'
  | 'edge'
  | 'projects';

export interface TopologyNode {
  id: string;
  name: string;
  sublabel: string;
  category: SubsystemCategory;
  tier: number; // 0=WAN/Gateways, 1=Physical/Virt Hypervisors, 2=VMs, 3=Core LXC, 4=Utility LXC, 5=Security/SIEM, 6=ELO AI, 7=Edge/IoT, 8=Projects
  ip?: string;
  port?: number;
  domain?: string;
  status: 'online' | 'standby' | 'alert';
  hardware?: {
    cpu?: string;
    ram: string;
    storage: string;
    node: string;
  };
  description: string;
  features: string[];
  technologies: string[];
  connections: string[]; // IDs of connected nodes
  position: { x: number; y: number; z: number };
  color: string;
  icon: string;
  metrics?: string;
  wikiDoc?: string;
}

export interface TopologyEdge {
  from: string;
  to: string;
  type: 'fiber' | 'mesh' | 'bridge' | 'ai_flow' | 'telemetry' | 'iot_radio';
  color: string;
  dashed?: boolean;
  speed?: number; // Packet velocity multiplier
}

